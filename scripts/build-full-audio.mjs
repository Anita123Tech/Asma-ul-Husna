import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = path.resolve(import.meta.dirname, "..");
const names = (await import(pathToFileURL(path.join(root, "src/data/names.js")).href)).default;
const wordTimings = (await import(pathToFileURL(path.join(root, "src/data/wordTimings.js")).href)).default;
const audioDir = path.join(root, "public/audio");
const fullAudioPath = path.join(audioDir, "asma-ul-husna-full.mp3");
const timelinePath = path.join(root, "src/data/audioTimeline.js");

const BITRATES = {
  2: [0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160, 0],
  3: [0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320, 0],
};
const SAMPLE_RATES = {
  2: [22050, 24000, 16000],
  3: [44100, 48000, 32000],
};
const SAMPLES_PER_FRAME = { 2: 576, 3: 1152 };

function parseFrameHeader(buffer, offset) {
  if (offset + 4 > buffer.length) return null;
  if (buffer[offset] !== 0xff || (buffer[offset + 1] & 0xe0) !== 0xe0) return null;

  const versionBits = (buffer[offset + 1] >> 3) & 0x03;
  const layerBits = (buffer[offset + 1] >> 1) & 0x03;
  if (versionBits !== 2 && versionBits !== 3) return null;
  if (layerBits !== 1) return null;

  const bitrateIndex = (buffer[offset + 2] >> 4) & 0x0f;
  const sampleRateIndex = (buffer[offset + 2] >> 2) & 0x03;
  const padding = (buffer[offset + 2] >> 1) & 0x01;
  const bitrate = BITRATES[versionBits][bitrateIndex];
  const sampleRate = SAMPLE_RATES[versionBits][sampleRateIndex];
  if (!bitrate || !sampleRate) return null;

  const samples = SAMPLES_PER_FRAME[versionBits];
  const frameLength = versionBits === 3
    ? Math.floor((144000 * bitrate) / sampleRate) + padding
    : Math.floor((72000 * bitrate) / sampleRate) + padding;

  return {
    frameLength,
    duration: samples / sampleRate,
  };
}

function readFrames(buffer) {
  const frames = [];
  let offset = 0;

  if (buffer.subarray(0, 3).toString("ascii") === "ID3" && buffer.length >= 10) {
    const size = ((buffer[6] & 0x7f) << 21) | ((buffer[7] & 0x7f) << 14) | ((buffer[8] & 0x7f) << 7) | (buffer[9] & 0x7f);
    offset = 10 + size;
  }

  while (offset + 4 <= buffer.length) {
    const header = parseFrameHeader(buffer, offset);
    if (!header) {
      offset += 1;
      continue;
    }
    const end = offset + header.frameLength;
    if (end > buffer.length) break;
    frames.push({
      offset,
      length: header.frameLength,
      duration: header.duration,
    });
    offset = end;
  }

  return frames;
}

const buffers = [];
const segments = [];
let cursor = 0;

for (const name of names) {
  const filePath = path.join(audioDir, path.basename(name.audio));
  const buffer = fs.readFileSync(filePath);
  const frames = readFrames(buffer);
  if (!frames.length) throw new Error(`No MPEG frames in ${name.audio}`);

  const totalDuration = frames.reduce((total, frame) => total + frame.duration, 0);
  const timings = wordTimings[name.id];
  if (!timings || !timings.length) throw new Error(`No word timings for name ${name.id}`);

  const frameDuration = frames[0].duration;
  const desiredStart = Math.max(0, timings[0][0] - 0.12);
  const desiredEnd = Math.min(totalDuration, timings[timings.length - 1][1] + 0.3);
  const startFrame = Math.max(0, Math.floor(desiredStart / frameDuration));
  const endFrame = Math.min(frames.length, Math.ceil(desiredEnd / frameDuration));
  if (endFrame <= startFrame) throw new Error(`Empty trim for ${name.audio}`);

  const actualStart = startFrame * frameDuration;
  const duration = (endFrame - startFrame) * frameDuration;
  const words = timings.map(([start, end]) => [
    Number((cursor + start - actualStart).toFixed(3)),
    Number((cursor + end - actualStart).toFixed(3)),
  ]);

  for (let i = startFrame; i < endFrame; i += 1) {
    const frame = frames[i];
    buffers.push(buffer.subarray(frame.offset, frame.offset + frame.length));
  }

  segments.push({
    id: name.id,
    start: Number(cursor.toFixed(3)),
    end: Number((cursor + duration).toFixed(3)),
    duration: Number(duration.toFixed(3)),
    words,
  });
  cursor += duration;
}

const fullAudio = Buffer.concat(buffers);
fs.writeFileSync(fullAudioPath, fullAudio);

const lines = [
  "// Absolute start/end times (seconds) for public/audio/asma-ul-husna-full.mp3.",
  "// `words` holds absolute start/end times for each Arabic word.",
  "// Generated by scripts/build-full-audio.mjs from names.js and wordTimings.js.",
  "",
  "const audioTimeline = [",
];
for (const segment of segments) {
  lines.push(
    `  { id: ${segment.id}, start: ${segment.start}, end: ${segment.end}, duration: ${segment.duration}, words: ${JSON.stringify(segment.words)} },`,
  );
}
lines.push("];", "", "export default audioTimeline;", "");
fs.writeFileSync(timelinePath, lines.join("\n"), "utf8");

console.log(`Wrote ${path.relative(root, fullAudioPath)} (${(fullAudio.length / 1024).toFixed(1)} KiB, ${cursor.toFixed(3)}s)`);
console.log(`Wrote ${path.relative(root, timelinePath)} (${segments.length} segments)`);
